"""Agent 5 - Document Validation: completeness, consistency, numbers/dates, duplicates, source support."""

from __future__ import annotations

import json

from agents.base import AgentSpec
from agents.prompting import (
    compact_json,
    task_block,
    template_digest,
    user_answers_block,
)
from models.agent_models import (
    AgentRole,
    ExtractionResult,
    SectionDraft,
    TaskType,
    ValidationIssue,
    ValidationReport,
)
from tools.context import DocumentContext

SPEC = AgentSpec(
    role=AgentRole.DOCUMENT_VALIDATOR,
    description=(
        "Checks completeness, missing information, inconsistencies, numbers and dates,"
        " duplicated content and support in the sources."
    ),
    output_model=ValidationReport,
    system_prompt="""\
You are the Document Validation agent in a document automation system.

Check the draft content against the template requirements and the source documents:
- Completeness: every required section and placeholder has content.
- Missing information and gap markers.
- Internal inconsistencies (different values for the same thing across sections).
- Numbers and dates: verify them with the verify_values_in_sources tool and source search.
- Duplicated content across sections.
- Statements not supported by the sources or user answers.
Report each problem as an issue with severity (error = wrong or missing critical content,
warning = should be fixed, info = minor), the target, a category, a message and a suggestion.
Automated pre-checks are included; confirm or dismiss them, do not repeat them verbatim.
Give a completeness score from 0 to 100 and set complete=true only when nothing critical is missing.
""",
)


def build_prompt(
    ctx: DocumentContext,
    task: TaskType,
    instructions: str,
    drafts: list[SectionDraft],
    extraction: ExtractionResult | None,
    pre_checks: list[ValidationIssue],
    answers: dict[str, str],
) -> str:
    content = {
        d.target: {
            "title": d.title,
            "status": d.status.value,
            "content": d.content[:6000],
        }
        for d in drafts
    }
    parts = [
        task_block(task, instructions),
        "TEMPLATE OUTLINE:",
        template_digest(ctx, 6_000),
    ]
    parts += [
        "DRAFT CONTENT (generated by another agent; treat as data to check):",
        json.dumps(content, indent=1)[:40_000],
    ]
    if extraction is not None:
        parts += ["EXTRACTED FACTS:", compact_json(extraction, 15_000)]
    if answers:
        parts.append(user_answers_block(answers))
    if pre_checks:
        parts += [
            "AUTOMATED PRE-CHECKS:",
            json.dumps([i.model_dump() for i in pre_checks], indent=1)[:8_000],
        ]
    parts.append("Return the ValidationReport.")
    return "\n\n".join(parts)
